export const getPatternForCharacter = (character: string): LetterPattern => {
  if (character.trim().length === 0) {
    return SPACE_PATTERN;
  }

  return LETTER_PATTERNS[character] ?? FALLBACK_PATTERN;
};

export const isEditableEmojiCharacter = (character: string): boolean => {
  return Boolean(LETTER_PATTERNS[character]) && character.trim().length > 0;
};
